#Entrada dos números

numero1 = float (input("O primeiro número: "))
numero2 = float (input("O segundo número: "))

#Cálculos e resultados

resultado = numero1 + numero2
print(f"{numero1} + {numero2} = {resultado}")

resultado = numero1 - numero2
print(f"{numero1} - {numero2} = {resultado}")

resultado = numero1 * numero2
print(f"{numero1} * {numero2} = {resultado}")

resultado = numero1 / numero2
print(f"{numero1} / {numero2} = {resultado:.2f}")

resultado = numero1 % numero2
print(f"{numero1} % {numero2} = {resultado}")

resultado = numero1 ** numero2
print(f"{numero1} ** {numero2} = {resultado}")
